
-- CIS 3610 Neighborhood Listing Platform
-- Migration 001: Initial database schema

-- 1. User profiles
CREATE TABLE public.profiles (
    user_id UUID PRIMARY KEY
        REFERENCES auth.users(id) ON DELETE CASCADE,
    display_name TEXT NOT NULL,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Property listings
CREATE TABLE public.properties (
    property_id INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    owner_id UUID NOT NULL
        REFERENCES public.profiles(user_id)
        ON DELETE RESTRICT,
    address JSONB NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    bedrooms INTEGER NOT NULL CHECK (bedrooms >= 0),
    bathrooms NUMERIC(4,1) NOT NULL CHECK (bathrooms >= 0),
    square_feet INTEGER NOT NULL CHECK (square_feet >= 0),
    amenities TEXT[] NOT NULL DEFAULT '{}',
    zip_code VARCHAR(5) NOT NULL
        CHECK (zip_code ~ '^[0-9]{5}$'),
    is_approved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Local business sponsors
CREATE TABLE public.sponsors (
    sponsor_id INTEGER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    business_name TEXT NOT NULL,
    description TEXT,
    website_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Property-to-sponsor relationships
CREATE TABLE public.property_sponsors (
    property_id INTEGER NOT NULL
        REFERENCES public.properties(property_id)
        ON DELETE CASCADE,
    sponsor_id INTEGER NOT NULL
        REFERENCES public.sponsors(sponsor_id)
        ON DELETE CASCADE,
    PRIMARY KEY (property_id, sponsor_id)
);

-- 5. Property inquiries
CREATE TABLE public.inquiries (
    inquiry_id BIGINT GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,
    property_id INTEGER NOT NULL
        REFERENCES public.properties(property_id)
        ON DELETE CASCADE,
    sender_id UUID NOT NULL
        REFERENCES public.profiles(user_id)
        ON DELETE RESTRICT,
    message TEXT NOT NULL
        CHECK (LENGTH(TRIM(message)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Supporting indexes
CREATE INDEX idx_properties_owner
    ON public.properties(owner_id);

CREATE INDEX idx_properties_approved
    ON public.properties(is_approved);

CREATE INDEX idx_inquiries_property
    ON public.inquiries(property_id);

-- Deny client access until explicit grants and
-- RLS policies are configured in Migration 002.

REVOKE ALL ON TABLE
    public.profiles,
    public.properties,
    public.sponsors,
    public.property_sponsors,
    public.inquiries
FROM anon, authenticated;


-- Enable RLS immediately, not after deployment.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.properties ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sponsors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.property_sponsors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;
