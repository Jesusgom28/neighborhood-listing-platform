
import Ajv2020 from "ajv/dist/2020";
import propertySchema from "../../schema/property.schema.json";

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
});

const validateSchema = ajv.compile(propertySchema);

export type PropertyInput = {
  address: {
    street: string;
    city: string;
    state: string;
  };
  price: number;
  bedrooms: number;
  bathrooms: number;
  square_feet: number;
  amenities: string[];
  zip_code: string;
  local_sponsors?: number[];
};

export function validateProperty(input: unknown): {
  valid: boolean;
  errors: string[];
  data?: PropertyInput;
} {
  if (
    typeof input !== "object" ||
    input === null ||
    Array.isArray(input)
  ) {
    return {
      valid: false,
      errors: ["Property must be a JSON object."],
    };
  }

  const candidate = input as Record<string, unknown>;
if (Object.prototype.hasOwnProperty.call(candidate, "property_id")) {
  return {
    valid: false,
    errors: ["property_id is generated by the database and cannot be submitted."],
  };
}

  // The database generates property_id automatically.
  // Sponsors are handled separately from the properties table.
  const schemaCandidate = {
    ...candidate,
    property_id: 1,
    local_sponsors: candidate.local_sponsors ?? [],
  };

  const valid = validateSchema(schemaCandidate);

  if (!valid) {
    return {
      valid: false,
      errors: (validateSchema.errors ?? []).map(
        (error) =>
          `${error.instancePath || "/"}: ${error.message ?? "Invalid value"}`
      ),
    };
  }

  const {
    address,
    price,
    bedrooms,
    bathrooms,
    square_feet,
    amenities,
    zip_code,
    local_sponsors,
  } = schemaCandidate as PropertyInput & { property_id: number };

  return {
    valid: true,
    errors: [],
    data: {
      address,
      price,
      bedrooms,
      bathrooms,
      square_feet,
      amenities,
      zip_code,
      local_sponsors,
    },
  };
}
